"""Build the volunteer app for the current OS with PyInstaller (it cannot cross-compile).

Reads TILINGVOL_SUBMIT_KEY (hex, the same value as on the server) and TILINGVOL_SERVER_URL from the
environment or from .env, writes them into the git-ignored module src/tilingvol/client/_k.py with the key
lightly scrambled, then builds dist/fe70(.exe). Run: uv run python scripts/build_client.py"""

import ast
import os
import secrets
import subprocess
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]
GENERATED = ROOT / "src" / "tilingvol" / "client" / "_k.py"
ENTRY = ROOT / "scripts" / "entry.py"
APP_NAME = "fe70"
SCRAMBLE_STEP = 73
RUNTIME_DLLS = ("msvcp140.dll", "msvcp140_1.dll", "msvcp140_2.dll", "concrt140.dll")
# the server needs none of these, and the client never imports them
EXCLUDES = [
    "fastapi",
    "uvicorn",
    "starlette",
    "pydantic",
    "httpx",
    "pytest",
    "IPython",
    "matplotlib",
]


def load_dotenv(path: Path) -> None:
    if not path.exists():
        return
    for line in path.read_text(encoding="utf-8").splitlines():
        line = line.strip()
        if line and not line.startswith("#") and "=" in line:
            key, value = line.split("=", 1)
            os.environ.setdefault(key.strip(), value.strip().strip('"').strip("'"))


def generated_module(key: bytes, server_url: str) -> str:
    mask = [secrets.randbelow(256) for _ in key]
    mixed = [
        k ^ m ^ ((i * SCRAMBLE_STEP) & 0xFF) for i, (k, m) in enumerate(zip(key, mask))
    ]
    return (
        "# generated by scripts/build_client.py; never commit\n"
        f"_A = {mixed[::-1]!r}\n"
        f"_B = {mask!r}\n"
        f"SERVER_URL = {server_url!r}\n\n\n"
        "def unpack() -> bytes:\n"
        f"    return bytes(a ^ b ^ ((i * {SCRAMBLE_STEP}) & 0xFF) for i, (a, b) in enumerate(zip(_A[::-1], _B)))\n"
    )


def main() -> None:
    load_dotenv(ROOT / ".env")
    key_hex = os.environ.get("TILINGVOL_SUBMIT_KEY")
    server_url = os.environ.get("TILINGVOL_SERVER_URL")
    if not key_hex or not server_url:
        raise SystemExit(
            "set TILINGVOL_SUBMIT_KEY and TILINGVOL_SERVER_URL (environment or .env)"
        )
    if not server_url.startswith(("https://", "http://")):
        raise SystemExit("TILINGVOL_SERVER_URL must start with https://")
    key = bytes.fromhex(key_hex)
    GENERATED.write_text(generated_module(key, server_url), encoding="utf-8")
    try:
        build()
    finally:
        GENERATED.unlink()  # keep the key out of the source tree; dev runs use the environment
    print(f"built {ROOT / 'dist' / APP_NAME}")


def build() -> None:
    command = [
        sys.executable,
        "-m",
        "PyInstaller",
        "--noconfirm",
        "--clean",
        "--onefile",
        "--windowed",
        "--name",
        APP_NAME,
        "--specpath",
        str(ROOT / "build"),
        "--paths",
        str(ROOT / "src"),
        "--collect-all",
        "ortools",
        "--collect-data",
        "certifi",  # the root list the app checks HTTPS against (tilingvol/client/tls.py)
        "--hidden-import",
        "tilingvol.client._k",
    ]
    for module in EXCLUDES:
        command += ["--exclude-module", module]
    subprocess.run(
        command + [str(ENTRY)], cwd=ROOT, check=True, env=build_environment()
    )
    check_runtime_dlls()


def build_environment() -> dict[str, str]:
    """PyInstaller bundles the first VC++ runtime it finds on PATH; another program's old copy (e.g. a JDK's
    MSVCP140.dll 14.36) makes OR-Tools crash inside Solve. Put the system copy first."""
    env = dict(os.environ)
    if sys.platform == "win32":
        system32 = str(Path(os.environ.get("SystemRoot", r"C:\Windows")) / "System32")
        env["PATH"] = system32 + os.pathsep + env.get("PATH", "")
    return env


def check_runtime_dlls() -> None:
    if sys.platform != "win32":
        return
    toc = ROOT / "build" / APP_NAME / "Analysis-00.toc"
    analysis = ast.literal_eval(toc.read_text(encoding="utf-8"))
    entries = [e for part in analysis if isinstance(part, list) for e in part]
    for entry in entries:
        if not (isinstance(entry, tuple) and len(entry) == 3):
            continue
        destination, source = str(entry[0]).lower(), str(entry[1]).lower()
        if Path(destination).name in RUNTIME_DLLS and "system32" not in source:
            raise SystemExit(f"{destination} was bundled from {source}, not System32")


if __name__ == "__main__":
    main()
